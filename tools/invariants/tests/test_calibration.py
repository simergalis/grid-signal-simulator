def test_scan_groups_signals_by_shared_band_key():
    """One key serves many signals, so a band chosen for one is imposed on all.
    The report has to surface that trade-off."""
    vals = jitter_with_steps()
    payloads = []
    for i, v in enumerate(vals):
        payloads.append(tick(sim_time_seconds=float(i * 5),
                             p_demand_mw=v, p_total_mw=v,
                             turbine_output_mw=v * 0.6))
    result = cal.scan(payloads)
    shared = {r["signal"] for r in result["by_band_key"]["deadband_power_mw"]}
    assert {"LOAD.p_demand_mw", "GEN.turbine_output_mw"} <= shared


def test_scan_proposes_no_values():
    """The scan reports curves. Choosing is a DR, not a computation."""
    text = cal.format_scan(cal.scan(ramp(jitter_with_steps())))
    assert "Nothing here proposes a value" in text
    for banned in ("recommended", "suggested band", "use "):
        assert banned not in text.lower()


def test_scan_output_is_deterministic():
    payloads = ramp(jitter_with_steps())
    a = json.dumps(cal.scan(payloads), sort_keys=True, default=str)
    b = json.dumps(cal.scan(payloads), sort_keys=True, default=str)
    assert a == b


def test_disabled_band_silences_a_signal_entirely():
    payloads = ramp([10.0 + i for i in range(20)])
    assert cal.emissions_at(payloads, SPEC, cal.DISABLED) == 0


def test_sweep_uses_the_real_detector_not_a_delta_count():
    """A slow ramp crossing one band in ten tiny steps emits once under
    hysteresis, but zero times under a naive |delta| >= band count. The scan must
    report one."""
    band = 1.0
    payloads = ramp([10.0 + i * 0.1 for i in range(11)])
    naive = sum(1 for d in cal._deltas([10.0 + i * 0.1 for i in range(11)])
                if d >= band)
    assert naive == 0
    assert cal.emissions_at(payloads, SPEC, band) == 1


def test_cli_refuses_to_run_without_a_catalogue(tmp_path, capsys):
    from nar001 import feed as feedcli
    p = tmp_path / "run-a.jsonl"
    with p.open("w") as fh:
        for i, v in enumerate([10.0, 11.0]):
            fh.write(json.dumps({"seq": i, "received_wall_utc": "x",
                                 "payload": tick(sim_time_seconds=float(i * 5),
                                                 p_demand_mw=v, p_total_mw=v)}) + "\n")
    rc = feedcli.main([str(tmp_path)])
    out = capsys.readouterr().out
    assert rc == 2
    assert "calibration scan" in out
    for k in required_parameters():
        assert k in out


