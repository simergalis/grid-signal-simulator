# ------------------------------------- regressions found by running the scan
def test_curve_has_more_than_one_point_on_uniform_steps():
    """Every percentile collapses to the same value when steps are uniform, so a
    percentile-only grid degenerates to a single point that cannot be read."""
    row = cal.scan_signal(ramp(jitter_with_steps(n_steps=4, per_step=20,
                                                 jitter=0.0)), SPEC)
    bands = [c["band"] for c in row["curve"]]
    assert len(bands) >= 5
    assert bands == sorted(bands)
    assert bands[0] < bands[-1]


def test_low_rate_signal_reports_raw_counts_not_a_rounded_rate():
    """Two changes in 800 ticks is 0.25 per 100 and rounds away to zero. The
    curve must carry the count."""
    vals = [10.0] * 400 + [20.0] * 400
    row = cal.scan_signal(ramp(vals), SPEC)
    small = row["curve"][0]
    assert small["emissions"] == 1
    assert small["per_100_ticks"] < 0.5      # would display as 0 if rounded


def test_dithering_signal_shows_a_cliff():
    """A signal with pure dither is silenced entirely by any band above its
    peak-to-peak, and the cliff is where the band should be read."""
    vals = [60.0 + (0.02 if i % 2 else -0.02) for i in range(200)]
    spec = next(s for s in REGISTRY if s.signal == "GEN.frequency_hz")
    payloads = [tick(sim_time_seconds=float(i * 5), frequency_hz=v)
                for i, v in enumerate(vals)]
    row = cal.scan_signal(payloads, spec)
    # Read the cliff from the scan, not from a literal: the observed floor here
    # is 0.040000000000006, so comparing bands against a hand-written 0.04 puts
    # the floor itself on the wrong side of the split.
    floor = row["noise_floor_estimate"]
    below = [c for c in row["curve"] if c["band"] <= floor]
    above = [c for c in row["curve"] if c["band"] > floor]
    assert below and above
    assert all(c["emissions"] > 0 for c in below)
    assert all(c["emissions"] == 0 for c in above)
    assert row["travel_ratio"] == pytest.approx(0.0, abs=0.02)   # retraces


def test_drifting_signal_has_no_cliff_and_is_labelled():
    """A monotonic drift never repeats a value, so no band silences it until the
    band exceeds the total range. The band is then a reporting policy."""
    vals = [0.95 - i * 0.0004 for i in range(400)]
    spec = next(s for s in REGISTRY if s.signal == "GEN.bess_soc_fraction")
    payloads = [tick(sim_time_seconds=float(i * 5), bess_soc_fraction=v)
                for i, v in enumerate(vals)]
    row = cal.scan_signal(payloads, spec)
    assert row["travel_ratio"] == pytest.approx(1.0, abs=1e-9)    # never retraces
    assert row["still_fraction"] == 0.0
    counts = [c["emissions"] for c in row["curve"]]
    assert counts == sorted(counts, reverse=True)
    assert counts[0] > counts[-1] > 0        # smooth decline, no cliff to zero


def test_rate_signal_silent_at_every_band_is_flagged():
    row = cal.scan_signal(ramp(jitter_with_steps()),
                          next(s for s in REGISTRY
                               if s.signal == "LOAD.p_demand_rate"))
