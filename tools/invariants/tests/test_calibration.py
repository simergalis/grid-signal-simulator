def test_travel_ratio_separates_dither_from_drift():
    """still_fraction cannot tell them apart -- an alternating signal never
    repeats a value either, so both read as 'always moving'. Net displacement
    over path length does separate them, and they need different bands."""
    dither = [60.0 + (0.02 if i % 2 else -0.02) for i in range(100)]
    drift = [60.0 + i * 0.02 for i in range(100)]
    spec = next(s for s in REGISTRY if s.signal == "GEN.frequency_hz")
    rows = {}
    for name, vals in (("dither", dither), ("drift", drift)):
        payloads = [tick(sim_time_seconds=float(i * 5), frequency_hz=v)
                    for i, v in enumerate(vals)]
        rows[name] = cal.scan_signal(payloads, spec)
    assert rows["dither"]["still_fraction"] == rows["drift"]["still_fraction"] == 0.0
    assert rows["dither"]["travel_ratio"] < 0.05
    assert rows["drift"]["travel_ratio"] == pytest.approx(1.0, abs=1e-9)
